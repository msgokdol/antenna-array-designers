assert(max(abs(expected-exported.equivalent_excitation_phase_deg)) < 1e-9 && ...
    abs(exported.x_mm(28)-C.X(4,4)) < 1e-9 && ...
    contains(fileread(tsvPath),'NOT a feed or physical reflector model'), ...
