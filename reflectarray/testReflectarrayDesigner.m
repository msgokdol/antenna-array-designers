    'opFreqGHz','retunePhase'});
oldProject.dxMM = 15; oldProject.dyMM = 15;
oldProject.freqGHz = 10; oldProject.formatVersion = 1;
upgraded = reflectarrayUpgradeProject(oldProject);
assert(upgraded.formatVersion == 5 && ...
    strcmp(upgraded.illuminationMode,'Horn') && ...
    abs(upgraded.dxLambda*299.792458/upgraded.designFreqGHz-15) < 1e-12 && ...
    abs(upgraded.dyLambda*299.792458/upgraded.designFreqGHz-15) < 1e-12, ...
    'Opening an old project must preserve its physical cell spacing.');
