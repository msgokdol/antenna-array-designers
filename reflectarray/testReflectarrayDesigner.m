assert(max(abs(rowShift(1:2:end))) < 1e-12 && ...
    max(abs(rowShift(2:2:end)-0.2)) < 1e-12, ...
    'Row stagger must shift alternate rows only.');
P.gridAngleDeg = 75;
P.rowStaggerLambda = 0.2;
