assert(isequal(A.referencePhaseDeg,designPhase) && ...
    abs(reflectarrayField(A,A.referencePhaseDeg,25,40)) < ...
    abs(reflectarrayField(A,A.idealPhaseDeg,25,40)), ...
    'Fixed design-frequency phases must show operating-frequency loss.');
P.opFreqGHz = 10; P.retunePhase = true;

