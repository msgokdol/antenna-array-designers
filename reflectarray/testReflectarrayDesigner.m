function testReflectarrayDesigner
% Numerical invariants and a focused standalone UI smoke test.
here = fileparts(mfilename('fullpath'));
addpath(here,'-begin');
P = struct('M',8,'N',8,'dxLambda',0.5,'dyLambda',0.5, ...
    'designFreqGHz',10,'opFreqGHz',10,'retunePhase',true, ...
    'feedMM',[0 0 150],'feedQ',4,'beamThetaDeg',0, ...
    'beamPhiDeg',0,'shape','Rectangle','taper','None');
A = reflectarrayAperture(P);
assert(abs(A.dxMM-0.5*299.792458/10) < 1e-12 && ...
    abs(A.dyMM-0.5*299.792458/10) < 1e-12, ...
    'Physical spacing must be set by design wavelength.');
E = reflectarrayField(A,A.idealPhaseDeg,0,0);
assert(abs(abs(E)-1) < 1e-12, ...
    'Ideal broadside reflection phases must cancel every feed path.');
complexPhase = complex(A.idealPhaseDeg,ones(size(A.idealPhaseDeg)));
assert(rejectsCalculation(@()reflectarrayField(A,complexPhase,0,0)) && ...
    rejectsCalculation(@()reflectarrayDirectivity(A,complexPhase)) && ...
    rejectsCalculation(@()reflectarrayField(A,A.idealPhaseDeg,1i,0)) && ...
    rejectsCalculation(@()reflectarrayPhaseMaps(A,complexPhase,P,41)) && ...
    rejectsCalculation(@()reflectarrayPhaseMaps(A,A.idealPhaseDeg,P,41+1i)) && ...
    rejectsCalculation(@()reflectarrayWriteCells(A,complexPhase,P, ...
        [tempname '.csv'],'csv')), ...
    'Public calculations and exports must reject complex phases or directions.');
Q = P;
Q.M = 2; Q.N = 2; Q.feedMM = [0 0 1e6]; Q.feedQ = 0;
Q.shape = 'Custom';
B = reflectarrayAperture(Q);
testTheta = 37; testPhi = 33;
analytic = abs(cos(pi*Q.dxLambda*sind(testTheta)*cosd(testPhi))* ...
    cos(pi*Q.dyLambda*sind(testTheta)*sind(testPhi)));
assert(abs(abs(reflectarrayField(B,B.idealPhaseDeg, ...
    testTheta,testPhi))-analytic) < 1e-6, ...
    'Off-axis field must match the analytic 2-by-2 array factor.');
square = P;
square.M = 20; square.N = 20; square.shape = 'Custom';
squareAperture = reflectarrayAperture(square);
squareAperture.amplitude(:) = 1;
cutAngles = [0 2 5 8 12];
alpha = pi*square.dxLambda*sind(cutAngles);
expectedSquare = abs(sin(square.N*alpha)./(square.N*sin(alpha)));
expectedSquare(1) = 1;
actualSquare = abs(reflectarrayField(squareAperture, ...
    squareAperture.referencePhaseDeg,cutAngles,zeros(size(cutAngles))));
assert(max(abs(actualSquare-expectedSquare)) < 1e-11, ...
    'A uniformly lit 20-by-20 reflectarray must reproduce the phased-array factor.');
plane = square;
plane.illuminationMode = 'Plane wave';
plane.incidentThetaDeg = 0; plane.incidentPhiDeg = 0;
planeA = reflectarrayAperture(plane);
planeField = abs(reflectarrayField(planeA,planeA.referencePhaseDeg, ...
    cutAngles,zeros(size(cutAngles))));
assert(all(planeA.amplitude(planeA.active) == 1) && ...
    max(abs(planeField-expectedSquare)) < 1e-11 && ...
    all(planeA.referencePhaseDeg(planeA.active) == 0), ...
    'Normal plane-wave illumination must give a uniform broadside aperture.');
sweepPlane = plane;
sweepPlane.beamThetaDeg = 30; sweepPlane.beamPhiDeg = 0;
sweepA = reflectarrayAperture(sweepPlane);
sweep = reflectarrayFrequencySweep(sweepPlane,sweepA.referencePhaseDeg, ...
    [8 10 12]);
expectedTheta = asind(10./[8 10 12]*sind(30));
assert(max(abs(sweep.peakThetaDeg-expectedTheta)) <= 0.5 && ...
    all(sweep.peakDbi >= sweep.targetDbi-1e-10) && ...
    sweep.pointingErrorDeg(2) < 0.3, ...
    'A fixed plane-wave phase map must show the predicted beam squint.');
centerD = reflectarrayDirectivity(sweepA,sweepA.referencePhaseDeg);
assert(abs(sweep.targetDbi(2)-10*log10(centerD.factor)) < 1e-10, ...
    'Sweep directivity at the phase-setting frequency must match the model.');
oneCell = plane;
oneCell.M = 2; oneCell.N = 2;
oneCell.activeMask = logical([1 0;0 0]);
oneA = reflectarrayAperture(oneCell);
oneD = reflectarrayDirectivity(oneA,oneA.referencePhaseDeg);
assert(abs(10*log10(oneD.factor)-10*log10(2)) < 1e-10, ...
    'A single upper-hemisphere scalar cell must have 3.01 dBi directivity.');
twoByTwo = rmfield(oneCell,'activeMask');
twoA = reflectarrayAperture(twoByTwo);
twoD = reflectarrayDirectivity(twoA,twoA.referencePhaseDeg);
diagonalKernel = sin(pi*sqrt(2))/(pi*sqrt(2));
expectedTwoD = 8/(1+diagonalKernel);
assert(abs(twoD.factor-expectedTwoD) < 1e-10, ...
    'The 2-by-2 directivity must match the exact cell-pair integral.');
overlap = twoByTwo;
overlap.activeMask = logical([1 1;0 0]);
overlap.xOffsetLambda = [0 -0.5;0 0];
overlap.yOffsetLambda = zeros(2);
overlapA = reflectarrayAperture(overlap);
opposing = overlapA.referencePhaseDeg;
opposing(1,2) = mod(opposing(1,1)+180,360);
overlapD = reflectarrayDirectivity(overlapA,opposing);
assert(isnan(overlapD.factor), ...
    'Perfectly cancelling coincident cells have undefined directivity.');
plane.incidentThetaDeg = 25; plane.incidentPhiDeg = 40;
plane.beamThetaDeg = 30; plane.beamPhiDeg = 115;
planeA = reflectarrayAperture(plane);
ui = [sind(25)*cosd(40) sind(25)*sind(40)];
uo = [sind(30)*cosd(115) sind(30)*sind(115)];
expectedPlanePhase = -planeA.k*(planeA.X*(ui(1)+uo(1)) + ...
    planeA.Y*(ui(2)+uo(2)));
assert(max(abs(exp(1i*deg2rad(planeA.idealPhaseDeg(:)))- ...
    exp(1i*expectedPlanePhase(:)))) < 1e-12 && ...
    abs(reflectarrayField(planeA,planeA.idealPhaseDeg,30,115)-1) < 1e-12, ...
    'Oblique plane-wave phases must focus coherently at the requested beam.');
planeMaps = reflectarrayPhaseMaps(planeA,planeA.referencePhaseDeg,plane,41);
assert(max(abs(exp(1i*deg2rad(planeMaps.spatialDeg(:)))- ...
    exp(1i*planeA.k*(planeA.X(:)*ui(1)+planeA.Y(:)*ui(2))))) < 1e-12, ...
    'Plane-wave phase map must show the incident linear phase gradient.');
planeCsv = [tempname '.csv'];
planeCleanup = onCleanup(@()deleteExportFiles(planeCsv,''));
reflectarrayWriteCells(planeA,planeA.referencePhaseDeg,plane,planeCsv,'csv');
planeExport = readtable(planeCsv);
expectedIncident = mod(rad2deg(planeA.k*(planeExport.x_mm*ui(1)+ ...
    planeExport.y_mm*ui(2))),360);
assert(max(abs(exp(1i*deg2rad(planeExport.incident_phase_deg))- ...
    exp(1i*deg2rad(expectedIncident)))) < 1e-11, ...
    'CSV incident phase must follow the selected plane-wave model.');
clear planeCleanup;
assert(max(abs(A.idealPhaseDeg-rot90(A.idealPhaseDeg,2)),[],'all') < 1e-10, ...
    'Centered-feed broadside map should have central symmetry.');

P.feedMM = [-35 20 150];
P.beamThetaDeg = 25; P.beamPhiDeg = 40;
A = reflectarrayAperture(P);
E = reflectarrayField(A,A.idealPhaseDeg,25,40);
assert(abs(E-1) < 1e-12, ...
    'Offset-feed steering must be coherent at the commanded direction.');
maps = reflectarrayPhaseMaps(A,A.referencePhaseDeg,P,51);
combined = exp(1i*deg2rad(-maps.spatialDeg+maps.progressiveDeg));
assert(max(abs(combined(:)-exp(1i*deg2rad(maps.reflectionDeg(:))))) < 1e-12, ...
    'Spatial delay and progressive phase must reconstruct the cell reflection phase.');
assert(isequal(size(maps.continuousDeg),[51 51]) && ...
    all(isfinite(maps.continuousDeg(:))), ...
    'The ideal continuous phase view must cover the whole nominal aperture.');
cellSamples = reflectarrayPhaseMaps(A,A.referencePhaseDeg,P,17);
continuousAtCells = cellSamples.continuousDeg(2:2:16,2:2:16);
assert(max(abs(exp(1i*deg2rad(continuousAtCells(:)))- ...
    exp(1i*deg2rad(A.referencePhaseDeg(:))))) < 1e-12, ...
    'The continuous phase law must equal the discrete law at cell centres.');
Rcheck = norm([A.X(3,5)-P.feedMM(1), ...
    A.Y(3,5)-P.feedMM(2),-P.feedMM(3)]);
kcheck = 2*pi*P.designFreqGHz/299.792458;
uxcheck = sind(P.beamThetaDeg)*cosd(P.beamPhiDeg);
uycheck = sind(P.beamThetaDeg)*sind(P.beamPhiDeg);
expectedPhase = kcheck*(Rcheck-A.X(3,5)*uxcheck-A.Y(3,5)*uycheck);
assert(abs(exp(1i*deg2rad(maps.reflectionDeg(3,5)))- ...
    exp(1i*expectedPhase)) < 1e-12, ...
    'An offset-feed, off-axis cell must match the published phase law.');
shifted = mod(A.idealPhaseDeg+73,360);
assert(abs(abs(reflectarrayField(A,shifted,25,40))-abs(E)) < 1e-12, ...
    'A common cell-phase offset must not alter the power pattern.');
changed = A.idealPhaseDeg;
changed(4,4) = mod(changed(4,4)+180,360);
assert(abs(reflectarrayField(A,changed,25,40)) < abs(E), ...
    'A wrong cell phase must reduce the target field.');
pairDirectivity = reflectarrayDirectivity(A,changed);
thetaGrid = 0:0.5:90;
phiGrid = 0:2:358;
[thetaMesh,phiMesh] = meshgrid(thetaGrid,phiGrid);
integrationField = reflectarrayField(A,changed,thetaMesh,phiMesh);
integratedPower = trapz(deg2rad(thetaGrid), ...
    sum(abs(integrationField).^2.*sind(thetaMesh),1)*deg2rad(2));
quadratureDirectivity = 4*pi/integratedPower;
assert(abs(10*log10(pairDirectivity.factor)- ...
    10*log10(quadratureDirectivity)) < 0.01, ...
    'Horn-fed, manually edited directivity must match angular integration.');

designX = A.X;
designPhase = A.referencePhaseDeg;
P.opFreqGHz = 12;
A = reflectarrayAperture(P);
assert(isequal(A.X,designX) && ...
    abs(abs(reflectarrayField(A,A.referencePhaseDeg,25,40))-1) < 1e-12, ...
    'Operating frequency must change propagation without moving cells.');
