oldStagger.yOffsetLambda(4,5) = -0.15;
oldStagger.formatVersion = 3;
oldRows = repmat((1:oldStagger.M).'-(oldStagger.M+1)/2,1,oldStagger.N);
migrated = reflectarrayUpgradeProject(oldStagger);
B = reflectarrayAperture(migrated);
oldLambdaMM = 299.792458/oldStagger.designFreqGHz;
oldPositionsX = B.baseX+B.baseY*cosd(75) + ...
    oldRows*oldStagger.rowStaggerLambda*oldLambdaMM*cosd(25) + ...
    oldStagger.xOffsetLambda*oldLambdaMM;
oldPositionsY = B.baseY*sind(75) + ...
    oldRows*oldStagger.rowStaggerLambda*oldLambdaMM*sind(25) + ...
    oldStagger.yOffsetLambda*oldLambdaMM;
assert(migrated.formatVersion == 5 && ...
    max(abs(B.X-oldPositionsX),[],'all') < 1e-10 && ...
    max(abs(B.Y-oldPositionsY),[],'all') < 1e-10, ...
    'Old staggered projects must keep every physical cell position.');

V = migrated;
V.freqUnit = 'GHz'; V.angleConvention = 'Theta / phi';
V.manualEnabled = false; V.manualPhaseDeg = [];
V.selected = [1 1]; V.selectedCells = [1 1];
reflectarrayValidateProject(V);
unselected = V;
unselected.selected = zeros(0,2);
unselected.selectedCells = zeros(0,2);
reflectarrayValidateProject(unselected);
badSelection = unselected;
