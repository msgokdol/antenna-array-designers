assert(rejectsProject(badSelection), ...
    'Saved cell selection must have a matching primary cell.');
bad = V; bad.M = 1;
assert(rejectsProject(bad),'Projects outside row-spinner bounds must be rejected.');
bad = V; bad.dxLambda = 11;
assert(rejectsProject(bad),'Projects outside spacing bounds must be rejected.');
bad = V; bad.feedMM(3) = 0;
assert(rejectsProject(bad),'Invalid feed locations must be rejected.');
bad = V; bad.incidentThetaDeg = 90;
assert(rejectsProject(bad),'Invalid plane-wave incidence must be rejected.');
bad = V; bad.gridAngleDeg = 180;
assert(rejectsProject(bad),'Projects outside lattice bounds must be rejected.');
bad = V; bad.manualEnabled = true; bad.manualPhaseDeg = NaN(V.M,V.N);
assert(rejectsProject(bad),'Nonfinite manual phases must be rejected.');
bad = V; bad.manualEnabled = true;
bad.manualPhaseDeg = 40000*ones(V.M,V.N);
assert(rejectsProject(bad), ...
    'Saved manual phases beyond the cell-spinner limits must be rejected.');
bad = V; bad.xOffsetLambda(1,1) = 1i;
assert(rejectsProject(bad),'Complex cell offsets must be rejected.');

P.taper = 'Hann (ideal amplitude)';
B = reflectarrayAperture(P);
assert(B.amplitude(1,1) < B.amplitude(4,4), ...
    'Hann taper must reduce edge-cell amplitude.');
