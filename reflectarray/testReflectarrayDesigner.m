steerTheta.Value = 90; steerTheta.ValueChangedFcn(steerTheta,[]);
assert(isempty(findall(sweepAxes,'Type','Line', ...
    'DisplayName','Commanded direction')), ...
    'Changing the model must invalidate stale sweep results.');
steerPhi.Value = 0; steerPhi.ValueChangedFcn(steerPhi,[]);
followBeam.Value = false; followBeam.ValueChangedFcn(followBeam,[]);
cutTheta.Value = 0; cutTheta.ValueChangedFcn(cutTheta,[]);
style.Value = 'Cartesian'; style.ValueChangedFcn(style,[]);
nullCut = findall(cart,'Type','Line','DisplayName','Assigned phase');
assert(isscalar(nullCut) && max(nullCut.YData) <= -39.9, ...
    'A broadside cut through a 2-by-2 array null must show the plot floor.');
absoluteDbi.Value = true; absoluteDbi.ValueChangedFcn(absoluteDbi,[]);
nullDbiCut = findall(cart,'Type','Line','DisplayName','Assigned phase');
assert(all(isfinite(nullDbiCut.YData)) && ...
    max(nullDbiCut.YData) <= cart.YLim(2)-40.9, ...
    'The dBi view must also show a null at its floor.');
fprintf('Reflectarray core and UI smoke test passed.\n');
end

